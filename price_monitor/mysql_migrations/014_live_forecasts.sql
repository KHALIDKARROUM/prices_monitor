CREATE TABLE IF NOT EXISTS live_forecasts (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    product ENUM('gasoil','brent','bitume') NOT NULL,
    instrument VARCHAR(64) NOT NULL,
    horizon SMALLINT UNSIGNED NOT NULL,
    horizon_unit ENUM('calendar_days','months') NOT NULL,
    model VARCHAR(64) NOT NULL,
    model_version VARCHAR(100) NOT NULL,
    origin_date DATE NOT NULL,
    target_date DATE NOT NULL,
    issued_at DATETIME NOT NULL,
    prediction DECIMAL(18,6) NOT NULL,
    baseline_prediction DECIMAL(18,6) NOT NULL,
    lower_bound DECIMAL(18,6) NULL,
    upper_bound DECIMAL(18,6) NULL,
    actual_value DECIMAL(18,6) NULL,
    actual_source_date DATE NULL,
    actual_collected_at DATETIME NULL,
    evaluated_at DATETIME NULL,
    error DECIMAL(18,6) NULL,
    absolute_error DECIMAL(18,6) NULL,
    baseline_error DECIMAL(18,6) NULL,
    baseline_absolute_error DECIMAL(18,6) NULL,
    interval_covered BOOLEAN NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_live_forecast_issue (instrument, origin_date, target_date, horizon, model_version),
    INDEX idx_live_forecasts_pending (product, instrument, target_date, actual_value),
    INDEX idx_live_forecasts_evaluated (product, instrument, evaluated_at, id)
) ENGINE=InnoDB;
