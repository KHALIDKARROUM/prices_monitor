CREATE TABLE IF NOT EXISTS forecast_model_candidates (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    product ENUM('gasoil','brent','bitume') NOT NULL,
    instrument VARCHAR(64) NOT NULL,
    horizon SMALLINT UNSIGNED NOT NULL,
    horizon_unit ENUM('calendar_days','months') NOT NULL,
    model ENUM('naive','holt') NOT NULL,
    implementation_version VARCHAR(100) NOT NULL,
    candidate_version VARCHAR(180) NOT NULL,
    status ENUM('candidate','shadow','production','rolled_back','rejected') NOT NULL,
    validation_mae DECIMAL(18,6) NULL,
    validation_samples INT UNSIGNED NOT NULL DEFAULT 0,
    calibration_coverage DECIMAL(10,6) NULL,
    shadow_min_samples INT UNSIGNED NOT NULL DEFAULT 30,
    promotion_min_improvement DECIMAL(10,6) NOT NULL DEFAULT 0.05,
    rollback_max_degradation DECIMAL(10,6) NOT NULL DEFAULT 0.10,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    promoted_at DATETIME NULL,
    rolled_back_at DATETIME NULL,
    reason VARCHAR(1000) NOT NULL DEFAULT '',
    UNIQUE KEY uq_forecast_model_candidate (instrument, horizon, candidate_version),
    INDEX idx_forecast_model_candidates_scope (product, instrument, horizon, status)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS forecast_model_events (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    candidate_id BIGINT UNSIGNED NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    from_status VARCHAR(32) NULL,
    to_status VARCHAR(32) NULL,
    reason VARCHAR(1000) NOT NULL DEFAULT '',
    samples INT UNSIGNED NULL,
    production_mae DECIMAL(18,6) NULL,
    candidate_mae DECIMAL(18,6) NULL,
    baseline_mae DECIMAL(18,6) NULL,
    improvement DECIMAL(10,6) NULL,
    interval_coverage DECIMAL(10,6) NULL,
    created_at DATETIME NOT NULL,
    INDEX idx_forecast_model_events_candidate (candidate_id, id DESC),
    CONSTRAINT fk_forecast_model_event_candidate FOREIGN KEY (candidate_id) REFERENCES forecast_model_candidates(id)
) ENGINE=InnoDB;
